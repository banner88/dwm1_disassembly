LibScanByFamily:
    ; S104 FIX: the list buffer is wMonList, not $C0D8. Vanilla shares ONE list
    ; buffer ($C0D8) between the roster lists and this library list; FX1 (S71)
    ; moved every bank-$12 READER of it to wMonList ($D001) but this B7 writer
    ; kept $C0D8, so the tab list / lookup read the roster list instead: every
    ; tab showed species 0-4.. (DrakSlime ...) and a lookup opened species =
    ; list INDEX — only the Slime tab looked right (ids 0-19 in order); an
    ; unseen id in that slot printed text id $FF -> freeze (user S104, Spirit
    ; tab). Same size: 3-byte `ld hl` at both sites.
    ld hl, wMonList                    ; blank the display buffer ($20 slots) to $FF
    ld bc, $0020
    ld a, $ff
    call FillNBytesWithRegA

    ld a, [wOPTN_and_Item_selection]   ; tab column (0..1)
    ld b, a
    add a
    add a
    add b                              ; A = column*5
    ld b, a
    ld a, [wMenu_selection]
    and $7f                            ; tab row (0..4)
    add b                              ; A = tab POSITION (page*5 + row)
    call LibTabToFamily                ; S104 r5: -> the family shown there (LibTabOrder)
    ld [$cac0], a                      ; preserve original $cac0 semantics

    add a                              ; F*2 (pointer table stride)
    ld e, a
    ld d, $00
    ld hl, LibFamilyPtrTable
    add hl, de
    ld a, [hl+]
    ld h, [hl]
    ld l, a                            ; HL -> this family's list: db count, ids...

    ld a, [hl+]                        ; A = member count
    ld [$c8e9], a                      ; total slots written = member count
    ld c, a                            ; C = remaining members
    ld b, $00                          ; B = seen count
    or a
    jr z, .done                        ; empty family -> buffer stays blank

    ld d, h
    ld e, l                            ; DE = source (member-id list)
    ld hl, wMonList                    ; HL = dest buffer ptr (S104: was $c0d8)
.loop:
    ld a, [de]                         ; A = species id (current member)
    push hl                            ; save dest (TestBitInArray clobbers HL)
    ld hl, $ca94                       ; seen-bit array base
    call TestBitInArray                ; in A=species id; Z=unseen; preserves B,C,DE
    pop hl
    jr z, .unseen
    ld a, [de]                         ; re-read species id (A clobbered)
    ld [hl], a                         ; seen -> write species id
    inc b                              ; seen count++
    jr .next
.unseen:
    ld [hl], $fe                       ; unseen -> blank marker (id $FE, blank name; NOT $E0 — that's Gorbunok now)
.next:
    inc hl
    inc de
    dec c
    jr nz, .loop
.done:
    ld a, b
    ld [$c8e8], a                      ; seen count
    ret

