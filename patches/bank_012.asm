; FollowerArtResolve12 — Phase N follower-art fork for the $12 copy (ItemSlotPtrTable,
; $65f2; supplies lineage parent icons AND menu/library follower art). Reader passes
; HL = (species+$10)*2 (species>=240 already shunted upstream at cp $f0). id 221-239 ->
; computed gfx-ID in wNewSpeciesGid (S105 G3; was a table); else original add-base. Byte-neutral:
; 32B resolver replaces 32 of the 785 trailing $00 padding bytes.
; =============================================================================
FollowerArtResolve12:                ; in: HL = (species+$10)*2
    ld a, h
    cp $01
    jr c, .normal
    jr nz, .high
    ld a, l
    cp $da
    jr c, .normal
.high:                               ; species 221-239: the gfx-ID is COMPUTED (S105 G3)
    ld a, l                          ; L = low byte of (species+$10)*2
    sub $da                          ; = (species-221)*2 = the follower's index in bank $7E
    ld [wNewSpeciesGid], a
    ld a, $7e                        ; overflow bank $7E (compiler bank species7e)
    ld [wNewSpeciesGid+1], a
    ld hl, wNewSpeciesGid            ; caller reads the word at HL (DE is dead here)
    ret
.normal:
    ld de, ItemSlotPtrTable
    add hl, de
    ret
