; Out: wMonList.. buffer (S104; was $C0D8, see the fix note) = one slot per family member ($FE if unseen, species id if
;        seen — vanilla semantics: undiscovered monsters keep their blank slot).
;      $C8E9 = total slots (= member count), $C8E8 = seen count.
; Cost: one table walk, ROM0 helpers only. Zero far-loads, zero scratch RAM.
; Capacity: emitter guarantees every family <= BUFFER_CAPACITY (32), so no
;        buffer overflow check is needed at runtime.
; =============================================================================
; -----------------------------------------------------------------------------
; S104 r5 — library tab DISPLAY ORDER (user: "put the spirit family BEFORE the
; ??? family … Just a display reorder"). The tab strip and the member scan
; both index by tab POSITION (page*5 + row); LibTabToFamily turns a position
; into the family shown there. Family bytes, codes, icons and every other
; family-indexed table are unchanged. Positions 11-15 map to themselves
; (blank tabs: mode-4 ids 11-15 are the empty string). Keep LibTabOrder ==
; editor2/core/gamedata.py DISPLAY_ORDER (test_compiler checks it).
; In: A = position. Out: A = family. Preserves BC/DE/HL.
; -----------------------------------------------------------------------------
LibTabToFamily:
    push hl
    ld hl, LibTabOrder
    add l
    ld l, a
    ld a, $00
    adc h
    ld h, a
    ld a, [hl]
    pop hl
    ret

