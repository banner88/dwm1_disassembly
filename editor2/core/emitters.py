def room_idx(room):
    return F.val(room['mapID']) - 0x6B


def room_tag(room):
    return f"CustomRoom{room_idx(room)}"


def banner(title, sub=None):
    bar = "; " + "=" * 77
    out = [bar, f"; {title}"]
    if sub:
        out += [f"; {s}" for s in sub]
    out.append(bar)
    return out


