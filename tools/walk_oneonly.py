def floors(p, rom_path, n, seed):
    """census_maze's rig on a running game `p` (in the field) of rom_path: n floors; per
    floor its items, then SetBrd_6db0 (the treasure room's 8 chests) and CallBrd_6ddb (the
    rare chest) run on the same floor (bank $16 is mapped at the builder's end).
    -> (Counter floor items, Counter chests, Counter rare chests, floors made)."""
    from collections import Counter
    from tools.census_maze import ENTRY, DONE, RNG1, RNG2, _read_floor
    mem = p.memory
    rnd = random.Random(seed)
    rom = open(rom_path, 'rb').read()
    # SetBrd_6db0 ($16:$6DB0, bank $16 entry 7) and CallBrd_6ddb ($16:$6DDB): the same
    # addresses in the original and every patched build (asserted on the bytes)
    e7 = rom[0x16 * 0x4000 + 1 + 2 * 7] | rom[0x16 * 0x4000 + 2 + 2 * 7] << 8
    assert e7 == SET_CHESTS, hex(e7)
    o = 0x16 * 0x4000 + RARE_CHEST - 0x4000
    assert rom[o] == 0xCD and rom[o + 17:o + 20] == bytes([0x11, 0x04, 0x6E]), rom[o:o + 20].hex()
    rare_fn = RARE_CHEST
    st = {'armed': True, 'phase': 0, 'left': n, 'inp': None}
    seen = Counter()
    chests = Counter()
    rare = Counter()

    def push_ret(addr):
        sp = (p.register_file.SP - 2) & 0xFFFF
        mem[sp] = addr & 0xFF
        mem[sp + 1] = addr >> 8
        p.register_file.SP = sp

    def at_entry(_):
        if not st['armed']:
            return
        inp = {'seed': rnd.randrange(65536), 'size': rnd.randrange(3, 16),
               'ft3': rnd.randrange(16), 'progress': rnd.randrange(4),
               'npc_state': rnd.randrange(8)}
        mem[RNG1], mem[RNG2] = inp['seed'] >> 8, inp['seed'] & 0xFF
        mem[0xC93D] = inp['size']
        mem[0xC938] = inp['ft3']
        mem[0xCAB4] = inp['progress']
        mem[0xC92D] = inp['npc_state']
        st['inp'] = inp
        st['armed'] = False
        st['phase'] = 0

    def at_done(_):
        if st['inp'] is None:
            return
        if st['phase'] == 0:
            g = _read_floor(mem)
            for it in g['items']:
                if it['kind'] & 0x0F == 0:              # an item kind (sub = the item id)
                    seen[it['sub']] += 1
            st['phase'] = 1
            push_ret(DONE[1])
            p.register_file.PC = e7                     # SetBrd_6db0: 8 chests
            return
        if st['phase'] == 1:
            for i in range(8):
                chests[mem[0xD9CF + i]] += 1
            st['phase'] = 2
            if rare_fn is not None:
                push_ret(DONE[1])
                p.register_file.PC = rare_fn
                return
        if st['phase'] == 2:
            for i in range(4):
                v = mem[0xD9CF + i]
                rare[v] += 1
        st['inp'] = None
        st['left'] -= 1
        if st['left'] > 0:
            st['armed'] = True
            p.register_file.PC = ENTRY[1]

    p.hook_register(*ENTRY, at_entry, None)
    p.hook_register(*DONE, at_done, None)
    mem[0xD8D7] = 0
    mem[0xC96D], mem[0xC96E], mem[0xC96C], mem[0xC88F] = 1, 1, 1, 1
    for _ in range(max(3000, 60 * n)):
        mem[0xCA39], mem[0xCA3A] = 0xFF, 0x7F
        p.tick()
        if st['left'] <= 0:
            break
    p.stop(save=False)
    return seen, chests, rare, n - st['left']


def s_floors(w):
    print(f'floors: {w.n_floors} maze floors made by the game — floor items + treasure / rare chests')
    from tools.pyboy_harness import boot, to_bedroom
    drop = {WARPWING, BEASTTAIL, 41}
    w.start('hall')                                  # this build, in the field (the user's save)
    p = w.p
    w.p = None
    seen, chests, rare, done = floors(p, w.rom, w.n_floors, 157)
    bad = {i: c for i, c in list(seen.items()) + list(chests.items()) + list(rare.items())
           if i in drop}
    w.check(f'{done} floors: {sum(seen.values())} floor items, {sum(chests.values())} chests, '
            f'{sum(rare.values())} rare-chest slots — no WarpWing / BeastTail / ShinyHarp',
            done == w.n_floors and not bad, str(bad))
    w.check('… the other items still lie there (Herbs, meats …)', seen.get(HERB, 0) > 0 and
            len(seen) > 5, str(dict(seen.most_common(6))))
    orig = os.path.join(REPO, 'data', 'DWM-original.gbc')
    p0 = boot(orig)
    if not to_bedroom(p0):
        raise SystemExit('the original ROM: the new game did not reach the bedroom')
    adv(p0, 200)
    s0, c0, _r0, d0 = floors(p0, orig, w.n_floors, 157)
    w.check(f'the control: the ORIGINAL ROM, the same {d0} floors — WarpWings on floors / in '
            'chests', s0.get(WARPWING, 0) + c0.get(WARPWING, 0) > 0,
            f'floors {s0.get(WARPWING, 0)}, chests {c0.get(WARPWING, 0)}')


def negative_rom(w):
    b, a = w.sym['IsOneOnly77']
    rom = bytearray(open(w.rom, 'rb').read())
    o = b * 0x4000 + a - 0x4000
    rom[o:o + 2] = b'\xa7\xc9'                       # and a / ret: nothing is one-only
    open(w.rom, 'wb').write(rom)
    w.negative = True
    print('NEGATIVE CONTROL: IsOneOnly77 = `and a / ret` (nothing is one-only)')


STEPS = {'guide': s_guide, 'buy': s_buy, 'vault': s_vault, 'give': s_give,
         'dresser': s_dresser, 'nest': s_nest, 'lose': s_lose, 'floors': s_floors}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--build', required=True)
    ap.add_argument('--project', required=True)
    ap.add_argument('--sav', required=True)
    ap.add_argument('--keep', required=True)
    ap.add_argument('--negative', action='store_true')
    ap.add_argument('--only', default=None)
    ap.add_argument('--floors', type=int, default=400)
    a = ap.parse_args()
    os.makedirs(a.keep, exist_ok=True)
    w = OneWalk(a.build, a.sav, a.keep, a.project)
    w.n_floors = a.floors
    d = json.load(open(a.project))
    ids = {r['id']: int(r['mapID'], 16) for r in d['custom']['rooms']}
    w.rooms = {'cities_fount': ids['cities_fount'], 'hall': ids['aviary'], 'perch': ids['perch']}
    w.dresser = (STABLE,) + DRESSER_AT
    if a.negative:
        negative_rom(w)
    steps = list(STEPS) if not a.only else a.only.split(',')
    for name in steps:
        try:
            STEPS[name](w)
        except Exception as e:                       # noqa: BLE001 — a step that crashes fails
            import traceback
            traceback.print_exc()
            w.check(f'{name} ran', False, repr(e))
    print(f'WALK: {"PASS" if not w.fails else "FAIL " + str(w.fails)} ({w.checks} checks)')
    return 1 if w.fails else 0


if __name__ == '__main__':
    sys.exit(main())
