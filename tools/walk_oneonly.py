#!/usr/bin/env python3
"""walk_oneonly.py — S157 (ROADMAP E9): ONE-ONLY items on the real screens (PyBoy on the
user's .sav) + the random gates' floors measured in the game.

The demo (examples/s157_oneonly_demo/build_demo.py) = the user's project + the game's
WarpWing PERMANENT (used-up chance 0) + THE AVIARY / THE PERCH. A permanent item is
ONE-ONLY: at most one in the bag + the Vault, never on a random gate floor / in its
chests, kept after a lost battle; the game's BeastTail / ShinyHarp are permanent already.
Every check reads RAM (the bag $CA51, the Vault $CA65, the shop list $C0D8, gold, flags)
and what the TEXT ENGINE was handed (CallTextEngine's tail $05E3: bank [$C824] + the
text's address) — screenshots are kept for the eye:

  guide   the AVIARY GUIDE (Cities_FOUNT, YES) -> THE AVIARY
  buy     the WING STALL lists the WarpWing + BeastTail (none held); the how-many window
          stops at 1 for the WarpWing (three UPs -> one bought, one price paid); the Herb
          still buys 3 at once; the next BUY's list has no WarpWing (held)
  vault   a WarpWing in the VAULT only (bag empty of it): the stall still hides it
  give    the WINGKEEPER (a conversation Give) with a WarpWing held: the text engine shows
          OneOnlyLine (bank $77) — "… already has a WarpWing." — not the "full" words;
          nothing given; without one: "You got a WarpWing!" + one in the bag
  dresser the game's own Stable dresser (flag $0090 clear, a WarpWing held): OneOnlyLine
          instead of "Found a WarpWing! But cannot carry …", the flag stays clear, still
          one WarpWing; without one: "[HERO] got a WarpWing!", the flag set
  nest    the NEST's "2 BeastTails" (story command give_item, count 2): exactly one comes;
          a second talk with one held: nothing
  lose    the BRUISER: a lost battle — the WarpWing (permanent -> kept on loss) stays
  floors  N maze floors generated by the game (the census_maze rig on this ROM: forced
          RNG / size / contents row 0-15): no floor item and no treasure chest
          (SetBrd_6db0 run on each floor) and no rare chest (CallBrd_6ddb) is a one-only
          item; the same rig on the ORIGINAL ROM finds WarpWings (the control)

  python3 tools/walk_oneonly.py --build DEMO/build/build --project DEMO/project.json \\
      --sav USER.sav --keep KEEP [--negative] [--only a,b] [--floors 400]

--negative: bank $77 IsOneOnly77 -> `and a / ret` in the ROM copy (nothing is one-only):
the stall / give / dresser / nest checks must FAIL (the loot is compile-time: its
control is the original ROM's floors, run every time).
Prints `ok` / `FAIL` per check and `WALK: PASS` / `WALK: FAIL n`.
"""
import argparse
import json
import os
import random
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, REPO)
from tools.pyboy_harness import adv, tap, GAME_MODE, TEXTBOX, SCRIPT_FLAGS     # noqa: E402
from tools.walk_regions import s_continue                                       # noqa: E402
from tools.walk_items import ItemWalk, BAG, VAULT, C905, C906                   # noqa: E402

HERB, WARPWING, BEASTTAIL = 1, 29, 38
STABLE = 0x05            # the Stable (map $05): its dresser = screen 2's examine spot (8, 0) -> script 15
DRESSER_AT = (28, 1, 'up')
SET_CHESTS, RARE_CHEST = 0x6DB0, 0x6DDB   # bank $16 SetBrd_6db0 (entry 7) / CallBrd_6ddb   # screen 2 = column 2 of the 4-wide screen grid: x + 20; stand below it
DRESSER_FLAG = 0x0090


class OneWalk(ItemWalk):
    def held(self, item):
        return self.bag().count(item) + self.vault().count(item)

    def clear_item(self, item):
        m = self.m
        for k in range(20):
            if m[BAG + k] == item:
                m[BAG + k] = 0xFF
        for k in range(40):
            if m[VAULT + k] == item:
                m[VAULT + k] = 0xFF

    def put_bag(self, item):
        k = self.slot(0xFF)
        if k is None:
            k = self.slot(0)
        self.m[BAG + k] = item

    def flag(self, n):
        """Event flag n: $D99B + n / 8, mask $80 >> (n % 8) (ROM0 $26D5 table)."""
        return bool(self.m[0xD99B + n // 8] & (0x80 >> (n % 8)))

    def set_flag(self, n, on):
        a = 0xD99B + n // 8
        if on:
            self.m[a] |= 0x80 >> (n % 8)
        else:
            self.m[a] &= ~(0x80 >> (n % 8)) & 0xFF

    def line_addr(self):
        return self.sym['OneOnlyLine']

    def saw_line(self, n0):
        b, a = self.line_addr()
        return any(bb == b and aa == a for bb, aa, _t in self.shown[n0:])

    def shop_list(self):
        out = []
        for k in range(20):
            v = self.m[0xC0D8 + k]
            if v in (0, 0xFF):
                break
            out.append(v)
        return out

    def buy_qty(self, pos, item, ups):
        """walk_items.shop_buy with the how-many window watched: `ups` UPs there, then
        $C8DD (the amount the window holds) is read right before the A that confirms it.
        -> (bought?, the amount confirmed)."""
        m = self.m
        n0 = self.bag().count(item)
        placed, qty = False, None
        for _ in range(40):
            if self.bag().count(item) > n0:
                break
            c905, c906, _t = self._stable()
            if c905 == 2:
                tap(self.p, 'a', hold=3, wait=6)
            elif c906 in (2, 4):
                if not placed:
                    m[0xC8E3] = pos // 4
                    m[0xC8E2] = pos % 4
                    adv(self.p, 4)
                    placed = True
                tap(self.p, 'a', hold=3, wait=6)
            elif c906 in (5, 6, 7):
                for _ in range(ups):
                    tap(self.p, 'up', hold=6, wait=12)
                adv(self.p, 4)
                qty = m[0xC8DD]
                tap(self.p, 'a', hold=3, wait=6)
            else:
                tap(self.p, 'a', hold=3, wait=6)
        ok = self.bag().count(item) > n0
        for _ in range(10):
            c905, c906, _t = self._stable(10)
            if c905 == 2:
                break
            tap(self.p, 'b', hold=3, wait=10)
        return ok, qty

    def buy_list(self):
        """From BUY / SELL / EXIT: BUY, then the list as the fill left it."""
        m = self.m
        self._stable()
        tap(self.p, 'a', hold=3, wait=6)
        self.wait(lambda: m[C906] >= 2, 900)
        adv(self.p, 60)
        lst = self.shop_list()
        for _ in range(10):
            c905, _c906, _t = self._stable(10)
            if c905 == 2:
                break
            tap(self.p, 'b', hold=3, wait=10)
        return lst


# ------------------------------------------------------------------ the steps
def s_guide(w):
    print('guide: the AVIARY GUIDE (Cities_FOUNT, YES) -> THE AVIARY')
    s_continue(w)
    m = w.m
    for k in range(12, 20):                         # room in the bag
        m[BAG + k] = 0xFF
    for it in (WARPWING, BEASTTAIL):
        w.clear_item(it)
    m[0xCA4B], m[0xCA4C], m[0xCA4D] = 0x10, 0x27, 0x00   # 10,000 G
    w.goto(w.rooms['cities_fount'], 0, 3, 5)
    w.face('up')
    w.talk([True])
    w.idle()
    w.check('the AVIARY GUIDE (YES) -> THE AVIARY', w.where()[0] == w.rooms['hall'],
            f'at ${w.where()[0]:02X}')
    w.save('hall')


def s_buy(w):
    print('buy: the WING STALL — one WarpWing at most, hidden while held')
    w.start('hall')
    m = w.m
    w.goto(w.rooms['hall'], 0, 2, 4)
    w.face('up')
    w.check('the stall opens (BUY / SELL / EXIT)', w.shop_open())
    lst = w.buy_list()
    w.check('none held: the list offers the WarpWing (29) and the BeastTail (38)',
            WARPWING in lst and BEASTTAIL in lst, str(lst))
    pos = lst.index(WARPWING) if WARPWING in lst else 0
    g0 = w.gold()
    ok, qty = w.buy_qty(pos, WARPWING, 3)            # three UPs at the how-many window
    w.snap('bought_wing')
    w.check('three UPs at "how many": the amount confirmed is 1 ($C8DD)', qty == 1, str(qty))
    w.check('bought exactly ONE WarpWing for one price (100 G)',
            ok and w.bag().count(WARPWING) == 1 and g0 - w.gold() == 100,
            f'bag {w.bag().count(WARPWING)}, gold {g0} -> {w.gold()}')
    lst = w.buy_list()
    w.snap('list_held')
    w.check('held: the next BUY list has no WarpWing; the BeastTail is still there',
            WARPWING not in lst and BEASTTAIL in lst, str(lst))
    hp = lst.index(HERB) if HERB in lst else 0
    n0 = w.bag().count(HERB)
    g0 = w.gold()
    w.shop_buy(hp, HERB, qty=3)
    w.check('the Herb (not one-only) still buys 3 at once',
            w.bag().count(HERB) - n0 == 3 and g0 - w.gold() == 24,
            f'+{w.bag().count(HERB) - n0}, gold {g0} -> {w.gold()}')
    w.close_all()
    w.save('bought')


def s_vault(w):
    print('vault: a WarpWing in the Vault only — the stall still hides it')
    w.start('bought')
    m = w.m
    w.clear_item(WARPWING)
    m[VAULT + next(k for k in range(40) if m[VAULT + k] in (0, 0xFF))] = WARPWING
    w.goto(w.rooms['hall'], 0, 2, 4)
    w.face('up')
    w.shop_open()
    lst = w.buy_list()
    w.check('Vault only: the list has no WarpWing', WARPWING not in lst and w.held(WARPWING) == 1,
            f'{lst}, held {w.held(WARPWING)}')
    w.close_all()


def s_give(w):
    print('give: the WINGKEEPER — the "already has one" line with one held, else the wing')
    w.start('bought')
    m = w.m
    w.goto(w.rooms['hall'], 0, 6, 5)
    w.face('up')
    n0 = len(w.shown)
    w.said.clear()
    w.talk()
    w.idle()
    w.snap('wingkeeper_held')
    w.check('held: the text engine showed OneOnlyLine (bank $77)', w.saw_line(n0),
            ' '.join(f'${b:02X}:{a:04X}' for b, a, _t in w.shown[n0:][-4:]))
    w.check('… nothing given (still one WarpWing)', w.held(WARPWING) == 1, str(w.bag()))
    w.clear_item(WARPWING)
    n0 = len(w.shown)
    w.said.clear()
    w.talk()
    w.idle()
    w.check('none held: one WarpWing given', w.held(WARPWING) == 1, str(w.bag()))
    w.check_said('… with its "got" words', 'aviary_wingkeeper_got')
    w.check('… and no OneOnlyLine', not w.saw_line(n0))
    # the line must not linger: a plain talk next shows its own words
    w.goto(w.rooms['hall'], 0, 6, 5)
    w.face('up')
    n0 = len(w.shown)
    w.talk()
    w.idle()
    w.check('held again: the line once more, and nothing given', w.saw_line(n0) and
            w.held(WARPWING) == 1, str(w.bag()))


def s_dresser(w):
    print("dresser: the game's own Stable dresser (script 15, flag $0090)")
    w.start('bought')
    m = w.m
    w.set_flag(DRESSER_FLAG, False)
    w.set_flag(0x00F1, False)
    w.set_flag(0x0035, True)          # the drawer holds the wing from here on (script 15)
    stable = w.dresser
    w.goto(stable[0], 0, stable[1], stable[2])
    w.face(stable[3])
    n0 = len(w.shown)
    w.talk()
    w.idle()
    w.snap('dresser_held')
    w.check('held: the dresser showed OneOnlyLine instead of "Found a WarpWing! But cannot '
            'carry …"', w.saw_line(n0),
            ' '.join(f'${b:02X}:{a:04X}' for b, a, _t in w.shown[n0:][-4:]))
    w.check('… its flag $0090 stays clear (the wing is still in the dresser)',
            not w.flag(DRESSER_FLAG))
    w.check('… still one WarpWing', w.held(WARPWING) == 1, str(w.bag()))
    w.clear_item(WARPWING)
    n0 = len(w.shown)
    w.talk()
    w.idle()
    w.snap('dresser_free')
    w.check('none held: "[HERO] got a WarpWing!", one in the bag, the flag set',
            w.held(WARPWING) == 1 and w.flag(DRESSER_FLAG) and not w.saw_line(n0),
            f'{w.bag()}, flag {w.flag(DRESSER_FLAG)}')


def s_nest(w):
    print('nest: "2 BeastTails" (story command give_item, count 2) -> exactly one')
    w.start('bought')
    w.clear_item(BEASTTAIL)
    w.goto(w.rooms['perch'], 0, 3, 4)
    w.face('up')
    w.said.clear()
    w.talk()
    w.idle()
    w.check('none held: one BeastTail (not two)', w.held(BEASTTAIL) == 1, str(w.bag()))
    w.check_said('… with the "got" words', 'perch_nest_got')
    w.said.clear()
    w.talk()
    w.idle()
    w.check('held: nothing more', w.held(BEASTTAIL) == 1, str(w.bag()))
    w.check_said('… the "full" words (the story command gave nothing)', 'perch_nest_full')


def s_lose(w):
    print('lose: the BRUISER — the WarpWing (permanent -> kept on loss) stays')
    w.start('bought')
    m = w.m
    if WARPWING not in w.bag():
        w.put_bag(WARPWING)
    w.goto(w.rooms['perch'], 0, 6, 5)
    w.face('up')
    w.party_hp_1()
    r = w.talk([True])
    w.check('the BRUISER fight started', r == 'battle', r)
    w.battle_lost()
    w.follow(1500, until=lambda: w.idle(600))
    w.check('lost: the WarpWing is still in the bag', WARPWING in w.bag(), str(w.bag()))
    del m


